const DIFFICULTY = { M1: 1, M2: 3, M3: 5, M4: 6, M5: 8, M6: 10 }

function buildRecord(level, item) {
  const [correct, ...rest] = item.o
  const position = item.q.length % item.o.length
  const options = [...rest]
  options.splice(position, 0, correct)
  return {
    subject: SUBJECT,
    question: item.q,
    options: options.map((text) => ({ text, isCorrect: text === correct })),
    correctAnswer: correct,
    explanation: item.e,
    difficulty: DIFFICULTY[level],
    cefrLevel: level,
    category: 'math',
    topic: item.t,
  }
}

function validate(record) {
  const problems = []
  if (record.options.length !== 4) problems.push('ตัวเลือกไม่ครบ 4')
  const correct = record.options.filter((o) => o.isCorrect)
  if (correct.length !== 1) problems.push(`มีข้อถูก ${correct.length} ข้อ`)
  if (correct[0]?.text !== record.correctAnswer) problems.push('เฉลยไม่ตรงกับตัวเลือก')
  if (new Set(record.options.map((o) => o.text.trim())).size !== 4) problems.push('ตัวเลือกซ้ำ')
  // คำอธิบายคณิตอาจเป็นการคำนวณล้วนได้ แต่ถ้ามีตัวอักษรอังกฤษปนต้องมีภาษาไทยกำกับด้วย
  if (record.explanation.trim().length < 6) problems.push('คำอธิบายสั้นเกินไป')
  if (/[A-Za-z]{4,}/.test(record.explanation) && !/[฀-๿]/.test(record.explanation)) problems.push('คำอธิบายเป็นภาษาอังกฤษล้วน')
  if (!record.topic) problems.push('ไม่มีหัวข้อ')
  return problems
}

async function main() {
  const records = []
  const failures = []
  for (const [level, items] of Object.entries(BANK)) {
    for (const item of items) {
      const record = buildRecord(level, item)
      const problems = validate(record)
      if (problems.length) failures.push(`${level} · ${item.q.slice(0, 40)} → ${problems.join(', ')}`)
      else records.push(record)
    }
  }

  if (failures.length) {
    console.error('ข้อสอบไม่ผ่านการตรวจ จึงไม่ลงฐานข้อมูล:')
    failures.forEach((f) => console.error('  -', f))
    process.exitCode = 1
    return
  }

  const existing = await prisma.question.findMany({ select: { question: true } })
  const seen = new Set(existing.map((q) => q.question.trim().toLowerCase()))
  let added = 0
  let skipped = 0
  for (const record of records) {
    if (seen.has(record.question.trim().toLowerCase())) {
      skipped += 1
      continue
    }
    await prisma.question.create({ data: record })
    seen.add(record.question.trim().toLowerCase())
    added += 1
  }

  console.log(`คณิตศาสตร์: ตรวจผ่าน ${records.length} ข้อ · เพิ่มใหม่ ${added} · ข้ามเพราะมีอยู่แล้ว ${skipped}`)
  const byLevel = await prisma.question.groupBy({
    by: ['cefrLevel'],
    where: { subject: SUBJECT },
    _count: true,
  })
  byLevel.sort((a, b) => a.cefrLevel.localeCompare(b.cefrLevel))
  console.log('จำนวนข้อต่อระดับ:', byLevel.map((l) => `${l.cefrLevel}=${l._count}`).join(' · '))
}

main()
  .catch((error) => {
    console.error('seed-math failed:', error)
    process.exitCode = 1
  })
  .finally(() => prisma.$disconnect())
