import { runAgent, AgentResult, normaliseConfidence } from './runner'
import { SUBJECTS, SubjectKey } from '../subjects'

/**
 * ตัวแทนที่ 8 — ผู้ตรวจงานเขียน
 *
 * ตัวนี้ต่างจากอีกเจ็ดตัวตรงที่ทำสิ่งที่ระบบกฎทำไม่ได้เลย ไม่ใช่ทำสิ่งเดิมให้ดีขึ้น
 *
 * ข้อสอบปรนัยวัดได้แค่ว่าผู้เรียน "จำได้ไหมว่าอันไหนถูก" (recognition)
 * แต่วัดไม่ได้ว่าเขา "ผลิตออกมาเองได้ไหม" (production) ซึ่งเป็นคนละทักษะ
 * ผู้เรียนจำนวนมากเลือกข้อถูกได้แต่เขียนประโยคเองไม่ถูก
 *
 * การตรวจงานเขียนด้วยกฎทำไม่ได้ เพราะภาษาที่ถูกต้องมีได้นับไม่ถ้วนรูปแบบ
 * ตัวตรวจไวยากรณ์แบบกฎจับได้แค่ความผิดพลาดที่ระบุไว้ล่วงหน้า และไม่รู้ว่า
 * งานเขียนชิ้นนั้นสื่อสารได้จริงหรือไม่
 *
 * PRD เดิมระบุการวัดทักษะการเขียนไว้ว่าอยู่นอกขอบเขต เพราะไม่มีวิธีทำ
 * เมื่อมีชั้น AI แล้วจึงทำได้ และเป็นการขยายความสามารถของแพลตฟอร์มจริง
 */

export interface WritingFeedback {
  /** ระดับที่ประเมินได้จากงานเขียนชิ้นนี้ */
  estimatedLevel: string
  /** ความมั่นใจ 0–100 — งานสั้นมากควรได้ค่าต่ำ */
  confidence: number
  /** สิ่งที่ทำได้ดี อย่างน้อยหนึ่งข้อเสมอ */
  strengths: string[]
  /** จุดที่ควรแก้ พร้อมตัวอย่างที่แก้แล้ว */
  issues: Array<{
    original: string
    corrected: string
    explanation: string
  }>
  /** คำแนะนำว่าควรฝึกอะไรต่อ */
  nextStep: string
}

/** ความยาวขั้นต่ำที่ประเมินได้อย่างมีความหมาย */
export const MIN_WORDS = 15

export function countWords(text: string, subject: SubjectKey): number {
  if (subject === 'english') {
    return text.trim().split(/\s+/).filter(Boolean).length
  }
  // ภาษาไทยไม่มีช่องว่างระหว่างคำ ใช้จำนวนอักขระหารด้วยความยาวคำเฉลี่ยแทน
  return Math.round(text.replace(/\s+/g, '').length / 4)
}

export async function assessWriting(input: {
  subject: SubjectKey
  /** ระดับปัจจุบันของผู้เรียน ใช้เป็นจุดอ้างอิง ไม่ใช่คำตอบ */
  currentLevel: string
  prompt: string
  text: string
  userId?: string
}): Promise<AgentResult<WritingFeedback>> {
  const definition = SUBJECTS[input.subject]

  const result = await runAgent<WritingFeedback>({
    agent: 'assess-writing',
    userId: input.userId,
    maxTokens: 1200,
    temperature: 0.2, // การประเมินต้องสม่ำเสมอ ป้อนงานเดิมควรได้ผลใกล้เคียงเดิม
    system: [
      `คุณเป็นผู้ตรวจงานเขียนวิชา${definition.name} ที่ตรวจให้ผู้เรียนไทย`,
      `ใช้เกณฑ์ ${definition.framework}`,
      '',
      'คำบรรยายแต่ละระดับ:',
      ...definition.levels.map((l) => `- ${l}: ${definition.levelDescriptions[l]}`),
      '',
      'วิธีประเมิน:',
      '- ประเมินจากงานเขียนชิ้นนี้เท่านั้น ไม่ใช่จากระดับเดิมของผู้เรียน',
      '  ระดับเดิมให้ไว้เป็นข้อมูลประกอบ ถ้างานเขียนดีหรือแย่กว่านั้นให้บอกตามจริง',
      '- ดูทั้งความถูกต้องของภาษา ความหลากหลายของคำ และความต่อเนื่องของเนื้อหา',
      '- งานที่สั้นมากหรือไม่ตรงโจทย์ ให้ confidence ต่ำ อย่าเดาระดับสูงจากงานที่มีข้อมูลน้อย',
      '',
      'กติกาของการให้ผลตอบกลับ:',
      `- estimatedLevel ต้องเป็นหนึ่งใน ${definition.levels.join(', ')} เท่านั้น`,
      '- strengths ต้องมีอย่างน้อย 1 ข้อเสมอ แม้งานจะยังอ่อน หาสิ่งที่ทำได้ให้เจอ',
      '- issues ไม่เกิน 4 ข้อ เลือกเฉพาะที่สำคัญที่สุด ไม่ต้องจับผิดทุกจุด',
      '- issues แต่ละข้อต้องยกข้อความจริงจากงานเขียนมาใส่ใน original ห้ามแต่งขึ้นเอง',
      '- corrected คือข้อความเดียวกันที่แก้ให้ถูกแล้ว',
      '- explanation เป็นภาษาไทย บอกว่าผิดหลักอะไร ไม่เกิน 1 ประโยค',
      '- nextStep เป็นภาษาไทย บอกว่าควรฝึกอะไรต่อให้เจาะจง ไม่ใช่ "ฝึกเขียนบ่อย ๆ"',
      '- ใช้น้ำเสียงให้กำลังใจ ผู้เรียนที่ถูกจับผิดอย่างเดียวจะเลิกฝึก',
      '',
      'ตอบเป็น JSON: {"estimatedLevel": string, "confidence": number, "strengths": [string], "issues": [{"original": string, "corrected": string, "explanation": string}], "nextStep": string}',
    ].join('\n'),
    user: [
      `ระดับปัจจุบันของผู้เรียน (ข้อมูลประกอบ): ${input.currentLevel}`,
      `โจทย์: ${input.prompt}`,
      '',
      'งานเขียนของผู้เรียน:',
      input.text,
    ].join('\n'),
  })

  // ตรวจว่าระดับที่ตอบมามีอยู่จริง ไม่งั้นถือว่าใช้ไม่ได้
  if (result.status === 'ok' && result.data) {
    if (!definition.levels.includes(result.data.estimatedLevel)) {
      return {
        ...result,
        status: 'error',
        data: null,
        message: `โมเดลตอบระดับ "${result.data.estimatedLevel}" ซึ่งไม่มีในเกณฑ์ของวิชานี้`,
      }
    }
    result.data.confidence = normaliseConfidence(result.data.confidence)

    // ตัดจุดที่อ้างข้อความซึ่งไม่มีอยู่จริงในงานเขียนออก
    // โมเดลบางครั้งแต่งประโยคขึ้นมาเองแล้วบอกว่าผู้เรียนเขียนผิด ซึ่งทำให้สับสนหนัก
    const normalised = input.text.replace(/\s+/g, ' ').toLowerCase()
    result.data.issues = (result.data.issues ?? []).filter((issue) =>
      normalised.includes((issue.original ?? '').replace(/\s+/g, ' ').toLowerCase())
    )
  }

  return result
}

