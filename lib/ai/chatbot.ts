import { runAgent, AgentResult } from './runner'
import { FAQ } from '../chat-faq'

/**
 * ตัวแทนที่ 7 — ผู้ช่วยตอบคำถาม (ชั้นสุดท้ายของแชทบอท)
 *
 * ทำงานเฉพาะคำถามที่สองชั้นแรกตอบไม่ได้
 *   ชั้น 1  คำถามเกี่ยวกับข้อมูลของผู้ใช้เอง → ตอบจากฐานข้อมูลตรง ๆ
 *   ชั้น 2  คำถามที่พบบ่อย → ตอบจากคลัง FAQ ที่เขียนไว้
 *   ชั้น 3  ที่เหลือ → ตัวนี้
 *
 * การเรียงแบบนี้ทำให้คำถามส่วนใหญ่ได้คำตอบทันทีโดยไม่เสียค่าเรียกโมเดล
 * และคำตอบเรื่องขั้นตอนกับตัวเลขจะถูกต้องเสมอ เพราะมาจากข้อมูลจริงหรือข้อความที่เขียนไว้
 * ไม่ใช่จากการเดาของโมเดล
 *
 * ตัวนี้ถูกจำกัดขอบเขตไว้แน่นหนา เพราะแชทบอทที่ตอบทุกเรื่องบนเว็บการศึกษา
 * เปิดช่องให้ถูกใช้ผิดวัตถุประสงค์ และตอบเรื่องที่เราไม่ได้รับประกันความถูกต้อง
 */

export interface ChatReply {
  /** คำตอบภาษาไทย */
  answer: string
  /** โมเดลตอบได้จริงหรือแค่บอกว่าไม่ทราบ ใช้ตัดสินว่าควรเสนอช่องทางติดต่อคนไหม */
  answered: boolean
}

/** สรุปสิ่งที่ระบบทำได้ ให้โมเดลใช้เป็นขอบเขต ไม่ต้องเดาเอง */
const PLATFORM_FACTS = [
  'LearnHub เป็นแพลตฟอร์มวัดระดับความสามารถและแนะนำคอร์สเรียน',
  'วัดระดับได้ 3 วิชา: ภาษาอังกฤษ (A1–C2 ตามเกณฑ์ CEFR), คณิตศาสตร์ (M1–M6), วิทยาศาสตร์ (S1–S6)',
  'ทุกวิชามี 6 ระดับ และระดับของแต่ละวิชาเก็บแยกกัน',
  'การประเมินหนึ่งครั้งมี 25 ข้อ ปรับความยากตามคำตอบ ตอบถูกติดกัน 3 ข้อเลื่อนขึ้น ตอบผิดติดกัน 2 ข้อลดลง',
  'หน้าผลสอบชี้หัวข้อที่ตอบผิดและแนะนำคอร์สที่สอนหัวข้อนั้น',
  'ชำระเงินด้วย QR พร้อมเพย์ แล้วกดแจ้งการโอน จากนั้นผู้ดูแลตรวจสอบและอนุมัติ',
  'สถานะการลงทะเบียน: รอชำระเงิน → รอตรวจสอบการชำระ → เรียนได้แล้ว หรือ ไม่อนุมัติ',
  'วิดีโอบทเรียนจะดูได้เมื่อสถานะเป็น "เรียนได้แล้ว" เท่านั้น',
  'ยังไม่มีระบบรีเซ็ตรหัสผ่านด้วยตัวเอง ต้องติดต่อผู้ดูแล',
  'ยังไม่มีแอปมือถือแยก ใช้ผ่านเว็บบนมือถือได้',
  'ยังไม่มีใบประกาศนียบัตรเมื่อเรียนจบ',
  'ยังไม่มีการวัดทักษะการพูดและการฟัง',
]

export async function answerQuestion(input: {
  question: string
  /** ข้อมูลของผู้ถาม ใส่เท่าที่มี ช่วยให้ตอบได้ตรงตัวขึ้น */
  context?: {
    name?: string
    levels?: Array<{ subject: string; level: string }>
    enrollments?: Array<{ title: string; status: string }>
  }
  /** บทสนทนาก่อนหน้า เพื่อให้ตอบคำถามต่อเนื่องได้ */
  history?: Array<{ role: 'user' | 'assistant'; content: string }>
  userId?: string
}): Promise<AgentResult<ChatReply>> {
  const contextLines: string[] = []

  if (input.context?.levels?.length) {
    contextLines.push(
      'ระดับปัจจุบันของผู้ถาม: ' +
        input.context.levels.map((l) => `${l.subject} ${l.level}`).join(', ')
    )
  }
  if (input.context?.enrollments?.length) {
    contextLines.push(
      'คอร์สที่ลงทะเบียนไว้: ' +
        input.context.enrollments.map((e) => `${e.title} (${e.status})`).join(', ')
    )
  }

  const conversation = (input.history ?? [])
    .slice(-6) // เก็บแค่ 6 ข้อความหลัง พอให้ต่อเนื่องโดยไม่บวมจนเปลืองโทเคน
    .map((m) => `${m.role === 'user' ? 'ผู้ถาม' : 'ผู้ช่วย'}: ${m.content}`)
    .join('\n')

  return runAgent<ChatReply>({
    agent: 'chatbot',
    userId: input.userId,
    maxTokens: 400,
    temperature: 0.4,
    system: [
      'คุณเป็นผู้ช่วยตอบคำถามของเว็บไซต์ LearnHub ตอบเป็นภาษาไทยเสมอ',
      '',
      'สิ่งที่รู้เกี่ยวกับระบบ:',
      ...PLATFORM_FACTS.map((f) => `- ${f}`),
      '',
      'หัวข้อที่มีคำตอบมาตรฐานอยู่แล้ว (ใช้เป็นแนวทางได้):',
      ...FAQ.slice(0, 8).map((f) => `- ${f.answer.slice(0, 90)}...`),
      '',
      'กติกาที่ต้องทำตามเคร่งครัด:',
      '- ตอบเฉพาะเรื่องที่เกี่ยวกับ LearnHub การวัดระดับ คอร์สเรียน และการใช้งานเว็บนี้',
      '- ถ้าถูกถามเรื่องนอกขอบเขต ให้บอกสุภาพว่าตอบได้เฉพาะเรื่องเกี่ยวกับ LearnHub แล้วตั้ง answered เป็น false',
      '- ห้ามแต่งข้อมูลที่ไม่ได้ระบุไว้ข้างบน โดยเฉพาะราคา จำนวน หรือกำหนดเวลา',
      '- ถ้าไม่แน่ใจ ให้บอกตรง ๆ ว่าไม่ทราบและแนะนำให้ติดต่อผู้ดูแล แล้วตั้ง answered เป็น false',
      '- ห้ามเฉลยข้อสอบหรือช่วยทำข้อสอบ ถ้าถูกขอให้ปฏิเสธและตั้ง answered เป็น false',
      '- ตอบสั้น กระชับ ไม่เกิน 4 ประโยค',
      '',
      'ตอบเป็น JSON: {"answer": string, "answered": boolean}',
    ].join('\n'),
    user: [
      contextLines.length ? `ข้อมูลของผู้ถาม:\n${contextLines.join('\n')}` : null,
      conversation ? `บทสนทนาก่อนหน้า:\n${conversation}` : null,
      `คำถาม: ${input.question}`,
    ]
      .filter(Boolean)
      .join('\n\n'),
  })
}
