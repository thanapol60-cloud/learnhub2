export interface FaqMatch {
  entry: FaqEntry
  score: number
}

/**
 * จับคู่คำถามกับรายการ FAQ
 *
 * ภาษาไทยไม่มีช่องว่างระหว่างคำ การตัดคำให้ถูกต้องต้องใช้พจนานุกรม
 * ที่นี่จึงใช้วิธีตรงไปตรงมาคือหาว่าคำสำคัญปรากฏเป็นสตริงย่อยหรือไม่
 * ซึ่งแม่นพอสำหรับชุดคำถามที่ขอบเขตจำกัดแบบนี้ และไม่ต้องพึ่งไลบรารีเพิ่ม
 */
export function matchFaq(question: string): FaqMatch | null {
  const text = question.toLowerCase().replace(/\s+/g, '')
  let best: FaqMatch | null = null

  for (const entry of FAQ) {
    const hits = entry.keywords.filter((k) => text.includes(k.toLowerCase().replace(/\s+/g, '')))
    if (hits.length === 0) continue

    // บางรายการกว้างเกินไป ต้องมีคำบ่งชี้เพิ่มด้วยจึงจะนับ
    if (entry.requires && !entry.requires.some((r) => text.includes(r))) continue

    // คำสำคัญที่ยาวกว่าบ่งชี้ได้แม่นกว่า จึงให้น้ำหนักมากกว่า
    const score = hits.reduce((sum, k) => sum + k.length, 0)
    if (!best || score > best.score) best = { entry, score }
  }

  // ต่ำกว่านี้ถือว่าเป็นการจับคู่ที่บังเอิญ ปล่อยให้ AI ตอบดีกว่าตอบผิด
  // ตอบผิดแต่ดูมั่นใจ เสียความเชื่อถือมากกว่าการบอกว่าไม่แน่ใจ
  return best && best.score >= 6 ? best : null
}
